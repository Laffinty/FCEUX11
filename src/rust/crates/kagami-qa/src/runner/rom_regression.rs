//! ROM regression harness (Track C — Task 1 / C-2).
//!
//! Re-implements the functionality of the original C++ `rom_regression_test.cpp`
//! in pure Rust. For each test ROM, the harness:
//!
//! 1. Loads the ROM via [`SutAdapter::load`].
//! 2. Runs `FRAMES_TO_RUN = 60` frames via [`SutAdapter::step`].
//! 3. After each frame, copies the visible 256x240 region of XBuf
//!    (61440 bytes) into a local buffer via [`SutAdapter::snapshot`]
//!    and computes the CRC32 of that buffer.
//! 4. Compares the collected hash sequence against the entry in
//!    `fixtures/golden_hashes.json` and reports any mismatches.
//!
//! Mirrors the C++ behaviour at `tests/rom_regression_test.cpp:189-330`:
//! - `setvbuf(stdout, NULL, _IONBF, 0)` — already handled by Rust stdio.
//! - Loads each ROM in the hard-coded `tests[]` table.
//! - 60 frames per ROM, CRC32 of `XBuf[0..256*240]` per frame.
//! - Compares against `fixtures/golden_hashes.json`; mismatches print
//!   up to 5 lines and bump the global `mismatches` counter.
//! - Exit 0 iff every ROM matches; otherwise exit 1.
//!
//! ## Schema freeze
//!
//! The harness does NOT introduce new manifest fields. It uses the
//! existing `tests.json` schema for invocation metadata (CTest name,
//! binary, args, expected exit code) and the existing
//! `golden_hashes.json` format (`name → { frames: [u32; 60] }`).
//!
//! ## CRC32 implementation
//!
//! The Rust side uses the existing `crc32fast` crate (already a
//! dependency of `fceux11-utils`, transitively available to
//! `kagami-qa`). The CRC polynomial matches IEEE 802.3 (same as the
//! C++ `CalcCRC32` -> `fceux11_rust_crc32` -> `crc32fast::Hasher` chain
//! at `src/utils/crc32.cpp:23-30`). Byte-identical results for any
//! given input.

