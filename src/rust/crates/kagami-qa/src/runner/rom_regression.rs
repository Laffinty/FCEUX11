/// Parsed view of a `golden_hashes.json` document.
///
/// Matches the C++ `readGoldenHashes` parser (rom_regression_test.cpp:49-145).
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct GoldenHashes {
    pub names: Vec<String>,
    pub frames: Vec<Vec<u32>>,
}

impl GoldenHashes {
    /// Parse the JSON document. Hand-rolled to mirror the C++ reader —
    /// the format is constrained (the file is generated by the same
    /// C++ writer, never edited by hand).
    ///
    /// State machine:
    ///
    /// ```text
    ///   Top ──{──▶ InObject ──"name"──▶ InObject (record name)
    ///                              ──"frames"──▶ ExpectingArray
    ///                                         ──[──▶ InArray
    ///                                                  ──num──▶ InArray
    ///                                                  ──]──▶ InObject
    ///                                                  ──}──▶ Top (record entry)
    /// ```
    ///
    /// The outer `{` puts us in `InObject` (where we look for ROM keys).
    /// The inner `{` is a no-op (we are still in `InObject`; the next
    /// `"frames"` key is what advances us to `ExpectingArray`).
    pub fn parse(json: &str) -> Self {
        let mut out = GoldenHashes::default();
        let mut chars = json.chars().peekable();
        let mut current_name = String::new();
        let mut current_frames: Vec<u32> = Vec::new();
        let mut in_string = false;
        let mut token = String::new();
        let mut state = ParseState::Top;

        while let Some(c) = chars.next() {
            // Inside a string: accumulate until closing quote.
            if in_string {
                if c == '"' {
                    in_string = false;
                    match state {
                        ParseState::Top | ParseState::InObject => {
                            // We just finished reading a key. If it's
                            // "frames", the next token is the array.
                            if token == "frames" {
                                state = ParseState::ExpectingArray;
                            } else {
                                // ROM name (key in the outer object).
                                current_name = token.clone();
                            }
                        }
                        ParseState::ExpectingArray => {
                            // The "frames" key was a known marker; we
                            // never reach ExpectingArray with another
                            // token, so this branch is unreachable.
                        }
                        ParseState::InArray => {
                            // Numbers come unquoted; this branch is
                            // also unreachable.
                        }
                    }
                } else {
                    token.push(c);
                }
                continue;
            }

            match c {
                '"' => {
                    in_string = true;
                    token.clear();
                }
                '{' => {
                    // Outer { or inner { — both leave us in InObject
                    // (the next token determines whether it's a ROM
                    // name or "frames").
                    state = ParseState::InObject;
                }
                '}' => {
                    // End of an object. If we have a name+frames, save
                    // them. State goes back to Top because the outer
                    // document is closing OR we just finished the inner
                    // object of the previous ROM. The next thing is
                    // either `,` (whitespace) or another key.
                    if !current_name.is_empty() {
                        out.names.push(current_name.clone());
                        out.frames.push(current_frames.clone());
                        current_name.clear();
                        current_frames.clear();
                    }
                    state = ParseState::Top;
                }
                '[' => {
                    if state == ParseState::ExpectingArray {
                        current_frames.clear();
                        state = ParseState::InArray;
                    }
                }
                ']' => {
                    if state == ParseState::InArray {
                        state = ParseState::InObject;
                    }
                }
                ',' | ':' | ' ' | '\t' | '\n' | '\r' => {
                    // Whitespace / structural punctuation: ignored.
                }
                c if c.is_ascii_digit() => {
                    if state == ParseState::InArray {
                        let mut num = String::new();
                        num.push(c);
                        while let Some(&nc) = chars.peek() {
                            if nc.is_ascii_digit() {
                                num.push(nc);
                                chars.next();
                            } else {
                                break;
                            }
                        }
                        if let Ok(v) = num.parse::<u32>() {
                            current_frames.push(v);
                        }
                    }
                }
                _ => {
                    // Unknown character — silently skip (mirrors C++
                    // permissive parser).
                }
            }
        }
        out
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ParseState {
    Top,
    InObject,
    ExpectingArray,
    InArray,
}

