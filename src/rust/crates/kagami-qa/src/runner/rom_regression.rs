/// Outcome of running the rom_regression harness once.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RomRegressionOutcome {
    /// Per-ROM CRC32 sequences collected from the harness.
    pub collected: BTreeMap<String, Vec<u32>>,
    /// Mismatches (rom_name → vec of (frame_idx, expected, actual)).
    pub mismatches: Vec<RomRegressionMismatch>,
    /// Total frames compared (sum of common length across all ROMs).
    pub total_compared: u32,
    /// True iff at least one ROM had no baseline entry.
    pub missing_baseline: Vec<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RomRegressionMismatch {
    pub rom_name: String,
    pub frame: usize,
    pub expected: u32,
    pub actual: u32,
}

/// CRC32 over a byte slice using the IEEE 802.3 polynomial. Equivalent
/// to `CalcCRC32(0, buf, len)` in the C++ harness.
pub fn crc32(buf: &[u8]) -> u32 {
    crc32_update(0, buf)
}

/// CRC32 with an explicit initial value (matches `CalcCRC32(crc, buf, len)`).
pub fn crc32_update(crc: u32, buf: &[u8]) -> u32 {
    let mut h = crc32fast::Hasher::new_with_initial(crc);
    h.update(buf);
    h.finalize()
}

