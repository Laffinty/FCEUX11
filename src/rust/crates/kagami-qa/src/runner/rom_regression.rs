/// Run the full harness against the supplied `GoldenHashes` baseline.
///
/// `workdir` is the directory in which `fixtures/...` paths resolve
/// (typically the `tests/` directory). `frame_source` produces the
/// per-frame XBuf region.
pub fn run_regression<A>(
    adapter: &mut A,
    golden: &GoldenHashes,
    workdir: &Path,
) -> RomRegressionOutcome
where
    A: SutAdapter + FrameSource,
{
    let mut collected: BTreeMap<String, Vec<u32>> = BTreeMap::new();
    let mut mismatches: Vec<RomRegressionMismatch> = Vec::new();
    let mut total_compared: u32 = 0;
    let mut missing_baseline: Vec<String> = Vec::new();

    for case in rom_regression_cases() {
        let path = resolve_rom_path(workdir, &case.filename);
        let crcs = match collect_frame_crcs(adapter, case, workdir, FRAMES_TO_RUN) {
            Ok(v) => v,
            Err(_) => {
                // C++ continues on ROM load failure (sets anyFailed = true).
                // Mirror that: record a "missing" entry so the run is
                // marked failed but the loop continues.
                missing_baseline.push(case.name.clone());
                continue;
            }
        };
        collected.insert(case.name.clone(), crcs.clone());

        let exp_idx = golden.names.iter().position(|n| n == &case.name);
        match exp_idx {
            None => missing_baseline.push(case.name.clone()),
            Some(idx) => {
                let expected = &golden.frames[idx];
                let compare = crcs.len().min(expected.len());
                for f in 0..compare {
                    total_compared += 1;
                    if crcs[f] != expected[f] {
                        if mismatches.len() < 5 {
                            mismatches.push(RomRegressionMismatch {
                                rom_name: case.name.clone(),
                                frame: f,
                                expected: expected[f],
                                actual: crcs[f],
                            });
                        }
                    }
                }
            }
        }
        let _ = path; // referenced for documentation; not used otherwise
    }

    RomRegressionOutcome {
        collected,
        mismatches,
        total_compared,
        missing_baseline,
    }
}

/// Format the regression summary the way the C++ harness prints it
/// (`printf("=== Results ===\n"); printf("Compared: %d frames\n", ...);`).
pub fn format_summary(outcome: &RomRegressionOutcome) -> String {
    let mut s = String::new();
    s.push_str("=== Results ===\n");
    s.push_str(&format!("Compared: {} frames\n", outcome.total_compared));
    s.push_str(&format!("Mismatches: {}\n", outcome.mismatches.len()));
    if !outcome.missing_baseline.is_empty() {
        s.push_str(&format!("Missing baseline for: {}\n", outcome.missing_baseline.join(", ")));
    }
    if outcome.mismatches.is_empty() && outcome.missing_baseline.is_empty() {
        s.push_str("RESULT: PASSED\n");
    } else {
        s.push_str("RESULT: FAILED\n");
    }
    s
}

pub fn regression_exit_code(outcome: &RomRegressionOutcome) -> i32 {
    if outcome.mismatches.is_empty() && outcome.missing_baseline.is_empty() {
        0
    } else {
        1
    }
}

/// Load `golden_hashes.json` from disk and parse it.
pub fn load_golden_hashes(path: &Path) -> Result<GoldenHashes, String> {
    let text = std::fs::read_to_string(path)
        .map_err(|e| format!("cannot read golden hashes '{}': {}", path.display(), e))?;
    Ok(GoldenHashes::parse(&text))
}

