/// Width of the visible XBuf region (matches rom_regression_test.cpp:14).
pub const FRAME_WIDTH: usize = 256;
/// Height of the visible XBuf region (matches rom_regression_test.cpp:15).
pub const FRAME_HEIGHT: usize = 240;
/// Visible XBuf region size in bytes.
pub const FRAME_BUF_SIZE: usize = FRAME_WIDTH * FRAME_HEIGHT;
/// Number of frames per ROM (matches rom_regression_test.cpp:16).
pub const FRAMES_TO_RUN: u32 = 60;

