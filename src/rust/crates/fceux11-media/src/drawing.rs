// DrawTextTrans / DrawTextTransWH — rasterize text into an 8-bit pixel buffer
// ---------------------------------------------------------------------------

/// Rasterize a NUL-terminated text string into `dest` using the 6×7 font.
///
/// Equivalent to the C++ `DrawTextTrans` + `DrawTextTransWH` combo.
/// `width` is the row stride in pixels (must be 256 for XBuf-style buffers).
/// `fgcolor` is the foreground palette index. `max_w`/`max_h` clip the
/// output rectangle; `border` (0/1/2) controls the soft shadow / outline
/// weight (matching the original C++ behavior, including the historical
/// `y<15` clamp bug preserved for bytewise equivalence).
#[unsafe(no_mangle)]
pub extern "C" fn fceux11_rust_drawing_draw_text_trans(
    dest: *mut u8,
    dest_len: usize,
    textmsg: *const c_char,
    width: u32,
    fgcolor: u8,
    _max_w: c_int,
    max_h: c_int,
    border: c_int,
) {
    if dest.is_null() || textmsg.is_null() || width != 256 {
        return;
    }
    if dest_len < (max_h as usize).min(64) * 256 {
        return;
    }

    let text = unsafe { cstr_to_bytes(textmsg) };
    let width = width as usize;

    // Zero the scratch buffer.
    TARGET_SCRATCH.with(|cell| {
        let mut target = cell.borrow_mut();
        for t in target.iter_mut() {
            *t = 0;
        }

        let mut x: i32 = 2;
        let mut y: i32 = 2;
        let beginx: i32 = 2;
        let mut max_x: i32 = x;
        let mut last_ny: i32 = 0;

        for &ch_raw in text {
            if ch_raw == b'\n' {
                x = beginx;
                y += 8;
                continue;
            }
            let ch = fix_joed_char(ch_raw);
            let wid = FONT6X7[ch * 8] as i32;

            if x + wid >= width as i32 {
                x = beginx;
                y += 8;
            }

            for ny_i in 0..7 {
                let d = FONT6X7[ch * 8 + 1 + ny_i as usize];
                for nx in 0..wid {
                    let pixel_color = (d >> (7 - nx as u8)) & 1;
                    let ty = (y + ny_i) as usize;
                    let tx = (x + nx) as usize;
                    if ty >= 62 {
                        // Out of vertical space (matches C++ goto textoverflow).
                        // Force break out of both loops.
                        return;
                    }
                    if pixel_color != 0 {
                        target[ty * 256 + tx] = 2;
                    } else {
                        target[ty * 256 + tx] = 1;
                    }
                }
                last_ny = ny_i;
            }
            x += wid;
            if max_x < x {
                max_x = x;
            }
        }

        max_x += 2;
        if max_x > width as i32 {
            max_x = width as i32;
        }
        let mut max_y: i32 = y + last_ny + 2;
        if max_y > 62 {
            max_y = 62;
        }

        // Composite the scratch buffer to the destination.
        unsafe {
            let dest_slice: &mut [u8] = std::slice::from_raw_parts_mut(dest, dest_len);
            for py in 0..max_y {
                for px in 0..max_x {
                    let offs = (py as usize) * width + (px as usize);
                    if offs >= dest_len {
                        continue;
                    }
                    let mut pixel_color: i32 = (target[py as usize * 256 + px as usize] as i32) * 100;

                    if border >= 1 {
                        if px >= 1 {
                            pixel_color += target[py as usize * 256 + (px - 1) as usize] as i32;
                        }
                        if px < (width as i32 - 1) {
                            pixel_color += target[py as usize * 256 + (px + 1) as usize] as i32;
                        }
                        if py >= 1 {
                            pixel_color += target[(py - 1) as usize * 256 + px as usize] as i32;
                        }
                        if py < (16 - 1) {
                            pixel_color += target[(py + 1) as usize * 256 + px as usize] as i32;
                        }
                    }
                    if border >= 2 {
                        if px >= 1 {
                            pixel_color += target[py as usize * 256 + (px - 1) as usize] as i32 * 10;
                        }
                        if px < (width as i32 - 1) {
                            pixel_color += target[py as usize * 256 + (px + 1) as usize] as i32 * 10;
                        }
                        if py >= 1 {
                            pixel_color += target[(py - 1) as usize * 256 + px as usize] as i32 * 10;
                        }
                        if py < (16 - 1) {
                            pixel_color += target[(py + 1) as usize * 256 + px as usize] as i32 * 10;
                        }

                        if px >= 1 && py >= 1 {
                            pixel_color += target[(py - 1) as usize * 256 + (px - 1) as usize] as i32;
                        }
                        if px < (width as i32 - 1) && py >= 1 {
                            pixel_color += target[(py - 1) as usize * 256 + (px + 1) as usize] as i32;
                        }
                        if px >= 1 && py < (16 - 1) {
                            pixel_color += target[(py + 1) as usize * 256 + (px - 1) as usize] as i32;
                        }
                        if px < (width as i32 - 1) && py < (16 - 1) {
                            pixel_color += target[(py + 1) as usize * 256 + (px + 1) as usize] as i32;
                        }

                        if px >= 2 {
                            pixel_color += target[py as usize * 256 + (px - 2) as usize] as i32;
                        }
                        if px < (width as i32 - 2) {
                            pixel_color += target[py as usize * 256 + (px + 2) as usize] as i32;
                        }
                        if py >= 2 {
                            pixel_color += target[(py - 2) as usize * 256 + px as usize] as i32;
                        }
                        if py < (16 - 2) {
                            pixel_color += target[(py + 2) as usize * 256 + px as usize] as i32;
                        }
                    }

                    if pixel_color >= 200 {
                        dest_slice[offs] = fgcolor;
                    } else if pixel_color >= 10 {
                        if dest_slice[offs] < 0xA0 {
                            dest_slice[offs] = 0xC1;
                        } else {
                            dest_slice[offs] = 0xD1;
                        }
                    } else if pixel_color > 0 {
                        dest_slice[offs] = 0xCF;
                    }
                }
            }
        }
    });
}

// ---------------------------------------------------------------------------
// FCEU_DrawNumberRow — save-state status digit row
// ---------------------------------------------------------------------------

/// Draw the 10-digit save-state status row into the pixel buffer.
///
/// `xbaf` is the base pointer (already offset to `(LastSLine - 34) * 256 - 4`
/// from `XBuf`, computed by the C++ wrapper). `nstatus[0..10]` flags which
/// digits are active. `cur` highlights one of the 10 cells (border color 4).
///
/// The C++ layout has a 21-byte tile overlap quirk that is preserved verbatim
/// (see `SSTAT` doc comment).
#[unsafe(no_mangle)]
pub extern "C" fn fceux11_rust_drawing_draw_number_row(
    xbaf: *mut u8,
    xbaf_len: usize,
    nstatus: *const c_int,
    cur: c_int,
) {
    if xbaf.is_null() || nstatus.is_null() {
        return;
    }
    // Each digit tile writes at most 13*21 = 273 bytes; 10 tiles span 2541.
    // Plus the border rectangle around `cur` adds ~52 extra cells. The C++
    // writes at offsets up to 12*256 + 20 + 10*22 = 3332, so require 3333.
    if xbaf_len < 13 * 256 + 22 * 11 {
        return;
    }
    let nstatus = unsafe { std::slice::from_raw_parts(nstatus, 10) };
    let buf = unsafe { std::slice::from_raw_parts_mut(xbaf, xbaf_len) };

    for z in 1..11 {
        let z_21 = z * 21 + z; // z*22, base column offset for digit z
        if nstatus[z % 10] != 0 {
            for y in 0..13 {
                for x in 0..21 {
                    let sidx = y * 21 + x + (z - 1) * 252;
                    let didx = y * 256 + x + z_21;
                    buf[didx] = SSTAT[sidx] ^ 0x80;
                }
            }
        } else {
            for y in 0..13 {
                for x in 0..21 {
                    let sidx = y * 21 + x + (z - 1) * 252;
                    let didx = y * 256 + x + z_21;
                    if SSTAT[sidx] != 0x83 {
                        buf[didx] = SSTAT[sidx] ^ 0x80;
                    } else {
                        buf[didx] = (buf[didx] & 0x0F) | 0xC0;
                    }
                }
            }
        }
        if cur == (z % 10) as i32 {
            // Border rectangle: top + bottom rows, left + right columns.
            for x in 0..21 {
                buf[x + z_21] = 4;
            }
            for x in 1..12 {
                buf[256 * x + z_21] = 4;
                buf[256 * x + z_21 + 20] = 4;
            }
            for x in 0..21 {
                buf[12 * 256 + x + z_21] = 4;
            }
        }
    }
}

// ---------------------------------------------------------------------------
// FCEU_DrawRecordingStatus — play/record/pause icon
// ---------------------------------------------------------------------------

/// Draw a status icon (play/record/pause/none) into the pixel buffer.
///
/// `base` is the destination pointer (already offset to
/// `(LastSLine - y) * 256 + 495 + x_offset` from the XBuf base, computed by
/// the C++ wrapper). `base_len` is the remaining byte count from `base` to
/// the end of XBuf — the worst-case write is `(14*256 + 14) = 3598` bytes
/// below `base`, so we require at least that.
///
/// `icon_kind`: 0 = none, 1 = play, 2 = record, 3 = pause. Each icon is
/// drawn with a black inner pass and a color-4 outer pass (matching the
/// C++ `drawstatus` two-pass shadow effect).
#[unsafe(no_mangle)]
pub extern "C" fn fceux11_rust_drawing_draw_status_icon(
    base: *mut u8,
    base_len: usize,
    icon_kind: u8,
) {
    if base.is_null() {
        return;
    }
    if (icon_kind as usize) >= SLINE_ICONS.len() {
        return;
    }
    // Worst-case write extent: y=14, x up to 14 → 14*256 + 14 = 3598 bytes.
    if base_len < 15 * 256 {
        return;
    }

    let slines = SLINE_ICONS[icon_kind as usize];
    let buf = unsafe { std::slice::from_raw_parts_mut(base, base_len) };

    // First pass: black shadow (color 0).
    let mut i = 0;
    while slines[i] != 99 {
        let sy = slines[i] as usize;
        let x_start = slines[i + 1] as usize;
        let x_end = slines[i + 2] as usize;
        let row = sy * 256;
        for x in x_start..x_end {
            buf[row + x] = 0;
        }
        i += 3;
    }
    // Second pass: light edge (color 4), offset -255 pixels in the row
    // (i.e. one pixel row up + 255 columns left, matching the C++ `XBuf -= 255`).
    i = 0;
    while slines[i] != 99 {
        let sy = slines[i] as usize;
        let x_start = slines[i + 1] as usize;
        let x_end = slines[i + 2] as usize;
        // C++: `XBuf -= 255` after the first pass — same row, column -255.
        let row = sy * 256;
        for x in x_start..x_end {
            // Guard against underflow when x < 255.
            if x >= 255 {
                buf[row + (x - 255)] = 4;
            }
        }
        i += 3;
    }
}

