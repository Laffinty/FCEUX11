/// Return the width (in pixels) of an ASCII character, or 0 for the spacebar.
#[unsafe(no_mangle)]
pub extern "C" fn fceux11_rust_drawing_font_width(ch: u8) -> u8 {
    FONT6X7[fix_joed_char(ch) * 8]
}

