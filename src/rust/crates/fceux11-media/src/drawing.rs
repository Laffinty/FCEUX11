    fn test_draw_text_line_bg_writes_c0() {
        let mut buf = [0u8; 14 * 256];
        // Seed with arbitrary low-nibble values to verify masking.
        for i in 0..buf.len() {
            buf[i] = (i & 0x0F) as u8;
        }
        fceux11_rust_drawing_draw_text_line_bg(buf.as_mut_ptr(), buf.len());
        for y in 0..14 {
            let offs = if y >= 7 { OTABLE[13 - y] } else { OTABLE[y] };
            for x in 0..256 {
                if x >= offs && x < (256 - offs) {
                    assert_eq!(
                        buf[y * 256 + x], 0xC0 | ((y * 256 + x) & 0x0F) as u8,
                        "row {y} col {x} should have C0 | low nibble"
                    );
                } else {
                    // Outside the dimmed area, low nibble is preserved.
                    assert_eq!(
                        buf[y * 256 + x], ((y * 256 + x) & 0x0F) as u8,
                        "row {y} col {x} outside dim region should be unchanged"
                    );
                }
            }
        }
    }

