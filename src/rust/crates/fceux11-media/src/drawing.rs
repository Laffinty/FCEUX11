// ---------------------------------------------------------------------------
// Per-thread scratch buffer for text rasterization (replaces C++ `static target[64][256]`)
// ---------------------------------------------------------------------------

thread_local! {
    static TARGET_SCRATCH: std::cell::RefCell<[u8; 64 * 256]> =
        const { std::cell::RefCell::new([0u8; 64 * 256]) };
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/// Map a raw character to a font index (0 = spacebar = ASCII 0x20).
/// Mirrors the C++ `FixJoedChar` logic: out-of-range chars clamp to 0.
#[inline]
fn fix_joed_char(ch: u8) -> usize {
    let c = ch as i32 - 32;
    if c < 0 || c > 98 { 0 } else { c as usize }
}

/// Map a NUL-terminated C string pointer to a Rust byte slice.
///
/// # Safety
/// `ptr` must point to a valid NUL-terminated C string, or be null.
unsafe fn cstr_to_bytes(ptr: *const c_char) -> &'static [u8] {
    if ptr.is_null() {
        return &[];
    }
    unsafe {
        // Compute length by scanning for NUL.
        let mut len = 0usize;
        while *ptr.add(len) != 0 {
            len += 1;
        }
        std::slice::from_raw_parts(ptr as *const u8, len)
    }
}

// ---------------------------------------------------------------------------
// DrawTextLineBG — dim the message-line background
// ---------------------------------------------------------------------------

/// Apply a 14-row dimmed background to a 256-wide pixel buffer.
///
/// The C++ version writes `(dest[y*256+x] & 0x0F) | 0xC0` for `x` in
/// `[offs, 256-offs)`, where `offs` comes from a symmetric `otable` lookup.
/// Each row is at `y*256`, so `len` must be `>= 14 * 256 = 3584` bytes.
///
/// `dest` may be null (no-op). Returns silently if `len` is too small.
#[unsafe(no_mangle)]
pub extern "C" fn fceux11_rust_drawing_draw_text_line_bg(
    dest: *mut u8,
    dest_len: usize,
) {
    if dest.is_null() || dest_len < 14 * 256 {
        return;
    }
    unsafe {
        let buf: &mut [u8; 14 * 256] = &mut *(dest as *mut [u8; 14 * 256]);
        for y in 0..14usize {
            let offs = if y >= 7 { OTABLE[13 - y] } else { OTABLE[y] };
            let row_start = y * 256;
            for x in offs..(256 - offs) {
                buf[row_start + x] = (buf[row_start + x] & 0x0F) | 0xC0;
            }
        }
    }
}

