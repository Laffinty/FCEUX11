NEW = (
    "uint8_t ppu_rust_bridge_cpu_read(uint32_t addr) {\n"
    "    if (g_ppu_state == nullptr) {\n"
    "        return 0;\n"
    "    }\n"
    "    // Session C (Phase 6.6): port C++ A2002 suppression / NMI-cancel\n"
    "    // behavior (src/ppu.cpp:608-632) to the Rust PPU bridge.\n"
    "    //\n"
    "    // The C++ engine gates this on `if (newppu)`, but in headless\n"
    "    // tests the `newppu` flag stays 0 (legacy PPU) \u2014 both legacy\n"
    "    // C++ and Rust PPU FAIL blargg 02-vbl_set_time with the same\n"
    "    // hash `4103C340` as a result. The Rust PPU path now needs the\n"
    "    // suppression explicitly, otherwise blargg vbl_set_time stays\n"
    "    // red across both engines (see \u00a76.6 Session C in\n"
    "    // docs/history/v2.1_phase6_batch_compat.md).\n"
    "    //\n"
    "    // Two prior attempts at porting failed because they used the C++\n"
    "    // frame layout's VBL-set boundary `(sl 240, cy 340)` /\n"
    "    // `(sl 241, cy 0/1)`, but the Rust PPU runs in VBL-first layout\n"
    "    // where VBL sets at `(sl 241, dot 1)` \u2014 the C++ boundary\n"
    "    // positions don't exist in the Rust scheduler. The fix is to use\n"
    "    // the *VBL-first* layout equivalents:\n"
    "    //   \u2022 Suppress window: `(sl 240, dot 340)` \u2014 last dot of the\n"
    "    //     post-render scanline, immediately before the frame-wrap\n"
    "    //     to (241, 0). The Rust scheduler's\n"
    "    //     `frame.rs::tick_dot` checks `vbl_suppressed_this_frame`\n"
    "    //     at the (241, 1) VBL-set tick and skips the set + NMI\n"
    "    //     when set, so the flag needs to be set 1 PPU dot before\n"
    "    //     (241, 0) in the VBL-first layout.\n"
    "    //   \u2022 NMI cancel window: `(sl 241, dot 1)` (the VBL-set dot\n"
    "    //     itself) and `(sl 241, dot 2)` (one PPU dot later). The\n"
    "    //     Rust PPU latches NMI as `state.nmi_pending` at (241, 1)\n"
    "    //     when VBL is set + NMI is enabled; the C++ bridge's\n"
    "    //     per-dot interleave polls `take_nmi_pending` to forward\n"
    "    //     it to `TriggerNMI()`. Calling `take_nmi_pending` (and\n"
    "    //     discarding the value) at (241, 1)/(241, 2) clears the\n"
    "    //     latch before the next poll \u2014 matching\n"
    "    //     `X6502_IRQEnd(FCEU_IQNMI)` semantics.\n"
    "    //\n"
    "    // mapper_mmc1 frame 0 regression check (Phase 5.3 + 6.1.d\n"
    "    // hazards): the suppression window is 1 PPU dot, not 1 CPU\n"
    "    // cycle, and the NMI cancel window is 2 PPU dots \u2014 both\n"
    "    // bounded by exact (sl, dot) equality, so mapper code that\n"
    "    // reads $2002 at any other dot is unaffected. The ppudead\n"
    "    // path (VBL-first layout) sets VBL at (241, 0) \u2014 outside both\n"
    "    // windows \u2014 so ppudead frames do not interact with the\n"
    "    // suppression logic.\n"
    "    if (addr == 0x2002) {\n"
    "        const int16_t sl = fceux11_ppu_get_scanline(g_ppu_state);\n"
    "        const uint16_t dot = fceux11_ppu_get_dot(g_ppu_state);\n"
    "        if (sl == 240 && dot == 340) {\n"
    "            // 1 PPU dot before the VBL set at (241, 1): mark\n"
    "            // suppression so the upcoming (241, 1) tick skips the\n"
    "            // VBL flag set + NMI assert. Mirrors\n"
    "            // `fceu11_ppu_mark_vbl_set_suppressed()` in src/ppu.cpp:338.\n"
    "            fceux11_ppu_mark_vbl_set_suppressed(g_ppu_state);\n"
    "        } else if (sl == 241 && (dot == 1 || dot == 2)) {\n"
    "            // At the VBL set dot (241, 1) or 1 dot after (241, 2):\n"
    "            // the read returns VBL=1 (the set just happened) and\n"
    "            // clears the flag, AND we pull /NMI back up before the\n"
    "            // CPU samples it. Mirrors `X6502_IRQEnd(FCEU_IQNMI)` in\n"
    "            // src/ppu.cpp:630. take_nmi_pending returns 1 if a\n"
    "            // pending NMI was latched; we discard the value (the\n"
    "            // NMI is *cancelled*, not delivered) so the next\n"
    "            // `ppu_rust_bridge_take_nmi` poll returns 0.\n"
    "            (void)fceux11_ppu_take_nmi_pending(g_ppu_state);\n"
    "        }\n"
    "    }\n"
    "    return fceux11_ppu_cpu_read(g_ppu_state, static_cast<uint16_t>(addr));\n"
    "}\n"
)
text = FILE.read_text(encoding='utf-8')
if NEW in text:
    print('already applied')
elif OLD not in text:
    print('ERROR: old text not found')
    sys.exit(1)
else:
    text = text.replace(OLD, NEW)
    FILE.write_text(text, encoding='utf-8')
    print('ok, new size:', FILE.stat().st_size)
